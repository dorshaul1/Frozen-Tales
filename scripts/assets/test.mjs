import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PNG } from 'pngjs';
import { at, read, png, normalize, validateImage, validateDefinition, build, validate } from './core.mjs';
const def=read('assets/definitions/kayak.json'),source=png('assets/source/kayak/n-idle-0.png');
assert.throws(()=>validateImage(new PNG({width:1,height:1}),def,'wrong'),/dimensions/);
const clone=()=>PNG.sync.read(PNG.sync.write(source));
const aa=clone();aa.data[3]=128;
assert.throws(()=>validateImage(aa,def,'alpha'),/antialiased/);
const opaque=clone();for(let i=3;i<opaque.data.length;i+=4)opaque.data[i]=255;
assert.throws(()=>validateImage(opaque,def,'opaque'),/padding|transparency|palette/);
const bad=clone();bad.data.set([255,0,255,255],(15*source.width+15)*4);
assert.throws(()=>validateImage(bad,def,'palette'),/palette/);
assert.throws(()=>validateDefinition({...def,frames:[def.frames[0],def.frames[0]]}),/duplicate/);
assert.throws(()=>validateDefinition({...def,frames:[{...def.frames[0],direction:'UP'}]}),/direction/);
assert.throws(()=>normalize(new PNG({width:source.width*2,height:source.height*2}),def),/source dimensions/);
const enlarged=new PNG({width:source.width*2,height:source.height*2});
for(let y=0;y<enlarged.height;y++)for(let x=0;x<enlarged.width;x++)enlarged.data.set(source.data.subarray((Math.floor(y/2)*source.width+Math.floor(x/2))*4,(Math.floor(y/2)*source.width+Math.floor(x/2))*4+4),(y*enlarged.width+x)*4);
const resized=normalize(enlarged,{...def,padding:0,normalization:{fit:'contain'}});
assert(resized.data.equals(source.data),'Nearest-neighbor scaling must preserve exact clusters');
build();const before=fs.readFileSync(at('assets/atlases/game.png'));const registry=fs.readFileSync(at('src/game/assets/catalog.ts'));
build();assert(before.equals(fs.readFileSync(at('assets/atlases/game.png'))),'Atlas build must be deterministic');
assert(registry.equals(fs.readFileSync(at('src/game/assets/catalog.ts'))),'Registry must be deterministic');
console.log('PASS dimensions, alpha, transparency, palette, frame/direction validation, nearest-neighbor processing, deterministic atlas and registry');
console.log(validate());
